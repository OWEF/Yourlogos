import {chromium} from "playwright-core";
import assert from "node:assert/strict";
import {resolve,dirname} from "node:path";
import {fileURLToPath,pathToFileURL} from "node:url";
import {mkdir} from "node:fs/promises";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const url=pathToFileURL(resolve(root,"experiments/two-encounter-branching-lab-v04-standalone.html")).href;
const shots=resolve(root,"test-results/cz114-branching-map");
await mkdir(shots,{recursive:true});
const browser=await chromium.launch({channel:"chrome",headless:true,args:["--no-sandbox","--allow-file-access-from-files"]});
try{
 for(const width of [320,390,768]){
  const ctx=await browser.newContext({viewport:{width,height:844},isMobile:width<=390,hasTouch:width<=390,deviceScaleFactor:width<=390?2:1});
  const page=await ctx.newPage(),errors=[],requests=[];
  page.on("pageerror",err=>errors.push(err.message));
  page.on("request",req=>{if(/^https?:/.test(req.url()))requests.push(req.url());});
  await page.goto(url,{waitUntil:"load"});
  await page.getByRole("tab",{name:/Trade-Off/}).waitFor();
  assert.equal(await page.locator(".influence-group [data-stance]").count(),3,"Relevance must be nested in influence question");
  assert.equal(await page.locator("#interactive > .relevance").count(),0,"No detached followup section");
  await page.getByRole("button",{name:/I considered it necessary/}).click();
  await page.getByRole("button",{name:"Mixed feelings"}).click();
  const slider=page.locator("#range-0");
  await slider.evaluate(el=>{el.value="6";el.dispatchEvent(new Event("input",{bubbles:true}));});
  assert.equal(await slider.evaluate(el=>el.isConnected),true);
  await page.getByRole("button",{name:"See what your choice raises"}).click();
  const seneca=await page.evaluate(()=>window.__encounterDebug);
  assert.equal(seneca.packet.quote.id,49);
  assert.equal(seneca.expression.complete,false);
  assert.match(seneca.expression.title,/When did optional become necessary/);
  // Follow the Woolf journey. The map MUST precede any result.
  await page.getByRole("tab",{name:/Decision Map/}).click();
  assert.equal(await page.locator("#interactive .journey-map").count(),1);
  assert.equal(await page.locator("#interactive .branch-node").count(),0);
  assert.equal(await page.locator("#reveal").count(),0);
  await page.locator("#map-start").click();
  assert.equal(await page.locator('[data-fork="resource"] .branch-node').count(),2);
  assert.equal(await page.locator('[data-fork="barrier"]').count(),0);
  await page.locator('[data-branch="resource"][data-value="income"]').click();
  assert.equal(await page.locator('[data-fork="resource"] .branch-node.chosen').count(),1);
  assert.equal(await page.locator('[data-fork="barrier"] .branch-node').count(),2);
  assert.equal(await page.locator('[data-fork="action"]').count(),0);
  await page.locator('[data-branch="barrier"][data-value="space"]').click();
  assert.equal(await page.locator('[data-fork="action"] .branch-node').count(),2);
  assert.equal(await page.locator("#reveal").count(),0);
  await page.locator('[data-branch="action"][data-value="protect"]').click();
  assert.equal(await page.locator(".journey-consequence").count(),1);
  assert.equal(await page.locator(".journey-consequence [data-stance]").count(),3);
  assert.equal(await page.locator("#result").isVisible(),false);
  assert.equal(await page.locator("#interactive .branch-node.chosen").count(),3);
  assert.equal(await page.locator("#reveal").count(),1);
  await page.screenshot({path:resolve(shots,"process-"+width+".png"),fullPage:true});
  await page.getByRole("button",{name:"Mixed feelings"}).click();
  await page.getByRole("button",{name:"See where this path leads"}).click();
  const path1=await page.evaluate(()=>window.__encounterDebug);
  assert.equal(path1.packet.quote.id,28);
  assert.equal(path1.packet.observation.resource,"income");
  assert.equal(path1.packet.observation.barrier,"space");
  assert.equal(path1.packet.observation.action,"protect");
  assert.equal(path1.expression.complete,false);
  assert.equal(await page.locator("#result .journey-map").count(),0,"Map must be a process, not post-result infographic");
  assert.equal(await page.locator("#result .recap-node").count(),3);
  await page.screenshot({path:resolve(shots,"result-"+width+".png"),fullPage:true});
  // Modify a previous branch; subsequent choices and previous result must reset.
  await page.locator('[data-branch="resource"][data-value="space"]').click();
  assert.equal(await page.locator('[data-fork="barrier"] .branch-node').count(),2);
  assert.equal(await page.locator('[data-fork="action"]').count(),0);
  assert.equal(await page.locator("#result").isVisible(),false);
  assert.equal(await page.locator("#reveal").count(),0);
  await page.locator('[data-branch="barrier"][data-value="access"]').click();
  await page.locator('[data-branch="action"][data-value="challenge"]').click();
  await page.getByRole("button",{name:"See where this path leads"}).click();
  const path2=await page.evaluate(()=>window.__encounterDebug);
  assert.equal(path2.packet.observation.resource,"space");
  assert.equal(path2.packet.observation.barrier,"access");
  assert.equal(path2.packet.observation.action,"challenge");
  assert.notEqual(path1.expression.summary,path2.expression.summary);
  await page.locator("#map-reset").click();
  assert.equal(await page.locator("#interactive .branch-node").count(),0);
  assert.equal(await page.locator("#result").isVisible(),false);
  assert.deepEqual(errors,[],"Page script errors at "+width);
  assert.deepEqual(requests,[],"Unexpected network calls at "+width);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
  assert.equal(overflow,false,"Horizontal overflow at "+width);
  process.stdout.write("PASS CZ-114 "+width+"px: nested influence, progressive fork, exclusive branch, reset, distinct endings\n");
  await ctx.close();
 }
}finally{await browser.close();}
