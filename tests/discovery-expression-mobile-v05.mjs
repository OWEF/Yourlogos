import {chromium} from "playwright-core";
import assert from "node:assert/strict";
import {resolve,dirname} from "node:path";
import {fileURLToPath,pathToFileURL} from "node:url";
import {mkdir} from "node:fs/promises";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const url=pathToFileURL(resolve(root,"experiments/two-encounter-discovery-expression-lab-v05-standalone.html")).href;
const screenshots=resolve(root,"test-results/cz115-expression");
await mkdir(screenshots,{recursive:true});
const browser=await chromium.launch({channel:"chrome",headless:true,args:["--no-sandbox","--allow-file-access-from-files"]});
try{
 for(const width of [320,390,768]){
  const context=await browser.newContext({viewport:{width,height:844},isMobile:width<500,hasTouch:width<500,deviceScaleFactor:width<500?2:1});
  const page=await context.newPage(),errors=[],remote=[];
  page.on("pageerror",e=>errors.push(e.message));
  page.on("request",r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
  await page.goto(url,{waitUntil:"load"});
  await page.getByRole("tab",{name:/Trade-Off/}).waitFor();
  assert.equal(await page.locator("#interactive .detail-option").count(),3);
  assert.equal(await page.locator("#interactive [data-stance]").count(),0);
  assert.equal(await page.locator("#result").isVisible(),false);
  await page.locator("#range-0").evaluate(el=>{el.value="6";el.dispatchEvent(new Event("input",{bubbles:true}));});
  assert.equal(await page.locator("#range-0").evaluate(el=>el.isConnected),true);
  assert.equal(await page.locator("#time-0").innerText(),"3h");
  await page.getByRole("button",{name:/I considered it necessary/}).click();
  assert.match(await page.locator(".nested-label").innerText(),/what made the commitment feel necessary/i);
  await page.locator('[data-reason-detail="consequences"]').click();
  await page.getByRole("button",{name:"See what your choice raises"}).click();
  const result=await page.evaluate(()=>window.__encounterDebug);
  assert.equal(result.packet.quote.id,49);
  assert.match(result.expression.discovery,/optional request can carry consequences/);
  assert.match(result.expression.title,/optional become necessary/);
  assert.equal(result.expression.stages.personalRelevance.includes("real cost"),true);
  assert.equal(await page.locator("#result .discovery-card").count(),1);
  assert.equal(await page.locator("#result .insight-reason").count(),1);
  assert.equal(await page.locator("#result .fingerprint-echo").count(),0);
  assert.equal(await page.locator("#result details[open]").count(),0);
  await page.screenshot({path:resolve(screenshots,"seneca-discovery-"+width+".png"),fullPage:true});
  await page.getByRole("button",{name:"Try another path"}).click();
  await page.getByRole("button",{name:/I genuinely wanted this/}).click();
  await page.locator('[data-reason-detail="intrinsic"]').click();
  await page.getByRole("button",{name:"See what your choice raises"}).click();
  const chosen=await page.evaluate(()=>window.__encounterDebug);
  assert.equal(chosen.expression.question,null);
  assert.equal(await page.locator("#result .open-question").count(),0);
  await page.getByRole("tab",{name:/Decision Map/}).click();
  assert.equal(await page.locator("#interactive [data-stance]").count(),0);
  assert.equal(await page.locator("#reveal").count(),0);
  await page.locator("#map-start").click();
  await page.locator('[data-branch="resource"][data-value="space"]').click();
  await page.locator('[data-branch="barrier"][data-value="access"]').click();
  await page.locator('[data-branch="action"][data-value="challenge"]').click();
  assert.equal(await page.locator("#interactive .branch-node.chosen").count(),3);
  assert.equal(await page.locator("#interactive .nested-relevance").count(),0);
  await page.getByRole("button",{name:"See where this path leads"}).click();
  const woolf=await page.evaluate(()=>window.__encounterDebug);
  assert.equal(woolf.packet.quote.id,28);
  assert.match(woolf.expression.discovery,/Creating privately and being heard publicly/);
  assert.match(woolf.expression.discovery,/obstacles lie in rules and institutions/);
  assert.equal(await page.locator("#result .journey-map").count(),0);
  assert.equal(await page.locator("#result .recap-node").count(),3);
  await page.screenshot({path:resolve(screenshots,"woolf-discovery-"+width+".png"),fullPage:true});
  await page.locator('[data-branch="resource"][data-value="income"]').click();
  assert.equal(await page.locator("#result").isVisible(),false);
  assert.equal(await page.locator('#interactive [data-fork="action"]').count(),0);
  assert.deepEqual(errors,[],"No client errors at "+width);
  assert.deepEqual(remote,[],"No remote requests from standalone HTML at "+width);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2),false,"No overflow at "+width);
  process.stdout.write("PASS CZ-115 "+width+"px: conditional deep discovery, no feeling survey, map path, reflective exit, no remote data\n");
  await context.close();
 }
}finally{await browser.close();}
